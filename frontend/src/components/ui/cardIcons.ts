/**
 * Card titles to header icons, first match wins. A card with a string title gets an icon
 * automatically, so every card in the app reads the same way; pass `icon` to Card to override.
 */
const RULES: [RegExp, LucideIcon][] = [
  [/^priority\b|top priorities/, ListChecks],
  [/diagnos/, Stethoscope],
  [/thesis evolution|what changed/, GitCompareArrows],
  [/leading indicators|kpi/, Activity],
  [/dimension profile/, Radar],
  [/profile/, IdCard],
  [/how stars work|stars scorecard|starting scorecard/, Star],
  [/glossary/, BookText],
  [/briefing|primer/, BookOpen],
  [/advantages/, TrendingUp],
  [/constraints/, ShieldAlert],
  [/tensions/, Scale],
  [/how you win/, Trophy],
  [/how the board scores|board score|board will see/, Landmark],
  [/scoreboard/, Medal],
  [/response score|strong leadership|design score/, Award],
  [/capability classes/, Cpu],
  [/simplif/, Info],
  [/thesis|opportunit/, Lightbulb],
  [/team's map|ai opportunity map/, Map],
  [/synthes/, Sparkles],
  [/learned|debrief|notes/, GraduationCap],
  [/delivery tips|your pitch|pitch/, Mic],
  [/capital|round 2 plan/, Banknote],
  [/financ|budget|ledger/, Wallet],
  [/portfolio|existing cards|your cards/, Briefcase],
  [/result drivers|drivers/, Network],
  [/operating model|workflow|design at a glance/, Workflow],
  [/measures|scorecard/, Gauge],
  [/playtest/, FlaskConical],
  [/pilot/, Rocket],
  [/evidence release|release/, FolderOpen],
  [/overrides|settings/, SlidersHorizontal],
  [/export/, Download],
  [/activity/, History],
  [/evidence|data room/, FileSearch],
  [/leadership|facilitator decision/, MessagesSquare],
  [/layers|cards/, Layers],
  [/compass|direction/, Compass],
  [/see|view/, Eye],
  [/table|register/, Table2],
]

/** The icon for a card title; a neutral dashboard icon when nothing matches. */
export function iconForTitle(title: string): LucideIcon {
  const t = title.toLowerCase()
  return RULES.find(([re]) => re.test(t))?.[1] ?? LayoutDashboard
}
