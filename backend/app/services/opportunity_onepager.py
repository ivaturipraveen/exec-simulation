"""One-page AI Opportunity Map for one company: the document a facilitator can send to the client.

Exactly one page, by construction: every block has a fixed area and long text is truncated, so the
page reads in two minutes. It holds only the company's own consented opportunities (OD-09) and
nothing generated by AI: the map, where to start, and what to fix first, all from the executives'
own scores. Follow-on support is framed as optional (CON-003).
"""

from __future__ import annotations

import unicodedata
from collections.abc import Sequence
from datetime import date
from io import BytesIO
from pathlib import Path
from typing import TYPE_CHECKING

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.utils import ImageReader, simpleSplit
from reportlab.pdfbase.pdfmetrics import stringWidth
from reportlab.pdfgen.canvas import Canvas

from app.core.errors import DomainError, NotFound

if TYPE_CHECKING:
    from app.schemas.views import OpportunityItem
    from app.services.game import GameService

LOGO = Path(__file__).resolve().parents[1] / "assets" / "brightcone-logo-on-dark.png"

NAVY = colors.HexColor("#14213D")
INK = colors.HexColor("#1B2333")
MUTED = colors.HexColor("#5B6475")
RULE = colors.HexColor("#D9DEE8")
WHITE = colors.white

QUADRANTS = {
    "act_now": ("Act now", colors.HexColor("#1E8E5A"), colors.HexColor("#E8F5EE")),
    "strategic": ("Strategic initiative", colors.HexColor("#1F4FA0"), colors.HexColor("#E9EFFA")),
    "quick_win": ("Selective quick win", colors.HexColor("#B7791F"), colors.HexColor("#FBF3E1")),
    "defer": ("Defer", colors.HexColor("#6B7280"), colors.HexColor("#EEF0F3")),
}
DIMS = ("data", "workflow", "owner", "controls")

PAGE_W, PAGE_H = letter
MARGIN = 40
CONTENT_W = PAGE_W - 2 * MARGIN


class OnePagerDisabled(DomainError):
    status_code = 404
    code = "onepager_disabled"


def _clean(text: str) -> str:
    """Plain text the built-in fonts can draw (they cover Windows-1252 only)."""
    text = unicodedata.normalize("NFKC", text or "").replace("→", "->").replace("≥", ">=").replace("≤", "<=")
    return " ".join(text.encode("cp1252", "replace").decode("cp1252").split())


def _lines(text: str, font: str, size: float, width: float, max_lines: int) -> list[str]:
    """Wrap to `width`, keeping at most `max_lines` and ending a cut line with an ellipsis."""
    lines = simpleSplit(_clean(text), font, size, width)
    if len(lines) <= max_lines:
        return lines
    kept = lines[:max_lines]
    last = kept[-1]
    while last and stringWidth(last + "...", font, size) > width:
        last = last[:-1].rstrip()
    kept[-1] = last + "..."
    return kept


def _text(
    c: Canvas, x: float, y: float, lines: Sequence[str], font: str, size: float, color, leading: float
) -> float:
    """Draw lines downwards from baseline `y`; returns the baseline after the last line."""
    c.setFont(font, size)
    c.setFillColor(color)
    for line in lines:
        c.drawString(x, y, line)
        y -= leading
    return y


def _ranked(items: Sequence[OpportunityItem]) -> list[OpportunityItem]:
    return sorted(items, key=lambda i: (-i.value, -i.readiness_avg, i.title))


def _blockers(item: OpportunityItem) -> str:
    low = sorted((d for d in DIMS if item.readiness.get(d, 0) < 4), key=lambda d: item.readiness.get(d, 0))
    return ", ".join(f"{d} ({item.readiness.get(d, 0)}/5)" for d in low) or "nothing"


def _header(c: Canvas, company: str, prepared: date) -> float:
    band = 92
    top = PAGE_H - band
    c.setFillColor(NAVY)
    c.rect(0, top, PAGE_W, band, stroke=0, fill=1)
    if LOGO.exists():
        logo = ImageReader(str(LOGO))
        w, h = logo.getSize()
        height = 34
        c.drawImage(logo, MARGIN, top + (band - height) / 2, width=height * w / h, height=height, mask="auto")
    right = PAGE_W - MARGIN
    c.setFillColor(colors.HexColor("#9DB8E8"))
    c.setFont("Helvetica-Bold", 8)
    c.drawRightString(right, top + 62, "AI OPPORTUNITY MAP")
    c.setFillColor(WHITE)
    name = _lines(company, "Helvetica-Bold", 20, 300, 1)[0]
    c.setFont("Helvetica-Bold", 20)
    c.drawRightString(right, top + 38, name)
    c.setFillColor(colors.HexColor("#C9D3E6"))
    c.setFont("Helvetica", 9)
    c.drawRightString(right, top + 22, f"{prepared:%B} {prepared.day}, {prepared.year}")
    return top


def _stats(c: Canvas, y: float, items: Sequence[OpportunityItem]) -> float:
    count = {k: sum(1 for i in items if i.quadrant == k) for k in QUADRANTS}
    tiles = [
        (str(count["act_now"]), "Act now", "high value, ready today", QUADRANTS["act_now"][1]),
        (
            str(count["strategic"]),
            "Strategic initiatives",
            "high value, build foundations first",
            QUADRANTS["strategic"][1],
        ),
        (
            f"{count['quick_win']} / {count['defer']}",
            "Quick wins / Defer",
            "only if cheap, or later",
            QUADRANTS["defer"][1],
        ),
    ]
    gap, h = 10, 50
    w = (CONTENT_W - 2 * gap) / 3
    for n, (number, label, hint, color) in enumerate(tiles):
        x = MARGIN + n * (w + gap)
        c.setStrokeColor(RULE)
        c.setFillColor(WHITE)
        c.roundRect(x, y - h, w, h, 6, stroke=1, fill=1)
        c.setFillColor(color)
        c.rect(x, y - h, 3, h, stroke=0, fill=1)
        c.setFont("Helvetica-Bold", 22)
        c.drawString(x + 14, y - 30, number)
        text_x = x + 14 + stringWidth(number, "Helvetica-Bold", 22) + 10
        room = x + w - 8 - text_x
        _text(
            c, text_x, y - 22, _lines(label, "Helvetica-Bold", 9.5, room, 1), "Helvetica-Bold", 9.5, INK, 12
        )
        _text(c, text_x, y - 34, _lines(hint, "Helvetica", 8, room, 1), "Helvetica", 8, MUTED, 10)
    return y - h


def _grid(c: Canvas, y: float, items: Sequence[OpportunityItem], height: float = 236) -> float:
    axis = 16
    gap = 4
    left = MARGIN + axis
    cell_w = (CONTENT_W - axis - gap) / 2
    cell_h = (height - axis - gap) / 2
    bottom = y - height + axis
    cells = {
        "strategic": (left, bottom + cell_h + gap),
        "act_now": (left + cell_w + gap, bottom + cell_h + gap),
        "defer": (left, bottom),
        "quick_win": (left + cell_w + gap, bottom),
    }
    for key, (x, cy) in cells.items():
        label, color, tint = QUADRANTS[key]
        group = _ranked([i for i in items if i.quadrant == key])
        c.setFillColor(tint)
        c.roundRect(x, cy, cell_w, cell_h, 6, stroke=0, fill=1)
        c.setFillColor(color)
        c.setFont("Helvetica-Bold", 8.5)
        c.drawString(x + 10, cy + cell_h - 16, f"{label.upper()}  ({len(group)})")
        line_y, size, leading = cy + cell_h - 31, 8.5, 11
        floor = cy + 8
        for n, item in enumerate(group):
            remaining = len(group) - n
            room = int((line_y - floor) // leading) + 1
            if remaining > 1 and room <= 1:
                _text(c, x + 10, line_y, [f"+ {remaining} more"], "Helvetica-Oblique", size, MUTED, leading)
                break
            lines = _lines(item.title, "Helvetica", size, cell_w - 30, 2 if room > 2 else 1)
            c.setFillColor(color)
            c.circle(x + 13, line_y + 3, 1.8, stroke=0, fill=1)
            line_y = _text(c, x + 20, line_y, lines, "Helvetica", size, INK, leading) - 2
            if line_y < floor:
                break
        if not group:
            _text(c, x + 10, line_y, ["None"], "Helvetica-Oblique", size, MUTED, leading)
    c.saveState()
    c.setFillColor(MUTED)
    c.setFont("Helvetica-Bold", 7)
    c.translate(MARGIN + 9, bottom + cell_h)
    c.rotate(90)
    c.drawCentredString(0, 0, "VALUE  (lower  |  higher)")
    c.restoreState()
    c.setFillColor(MUTED)
    c.setFont("Helvetica-Bold", 7)
    c.drawCentredString(left + cell_w + gap / 2, y - height + 4, "READINESS  (not ready yet  |  ready today)")
    return y - height


class _Panel:
    """A titled box of entries; each entry is a list of (text, font, size, color, max_lines) rows.

    Laid out once so the page can size the box to its content before drawing anything."""

    TOP, BOTTOM, ENTRY_GAP = 40, 12, 8

    def __init__(self, title: str, color, entries: list[list[tuple]], empty: str, width: float):
        self.title, self.color, self.width = title, color, width
        rows = entries or [[(empty, "Helvetica-Oblique", 9, MUTED, 3)]]
        self.blocks = [
            [
                (_lines(text, font, size, width - 24, n), font, size, col, size * 1.3)
                for text, font, size, col, n in entry
            ]
            for entry in rows
        ]

    @property
    def height(self) -> float:
        body = sum(sum(len(lines) * leading for lines, *_, leading in block) for block in self.blocks)
        return self.TOP + body + self.ENTRY_GAP * (len(self.blocks) - 1) + self.BOTTOM

    def draw(self, c: Canvas, x: float, y: float, h: float) -> None:
        c.setStrokeColor(RULE)
        c.setFillColor(WHITE)
        c.roundRect(x, y - h, self.width, h, 6, stroke=1, fill=1)
        c.setFillColor(self.color)
        c.rect(x, y - 4, self.width, 4, stroke=0, fill=1)
        c.setFont("Helvetica-Bold", 11)
        c.drawString(x + 12, y - 22, self.title)
        line_y = y - self.TOP
        for block in self.blocks:
            for lines, font, size, col, leading in block:
                line_y = _text(c, x + 12, line_y, lines, font, size, col, leading)
            line_y -= self.ENTRY_GAP


def render_onepager(company: str, items: Sequence[OpportunityItem], *, prepared: date | None = None) -> bytes:
    """Render the one-page map. `items` must be this company's own consented opportunities."""
    if not items:
        raise ValueError("No opportunities to render")
    prepared = prepared or date.today()
    buffer = BytesIO()
    c = Canvas(buffer, pagesize=letter)
    c.setTitle(f"AI Opportunity Map - {_clean(company)}")
    c.setAuthor("Brightcone.ai")

    y = _header(c, company, prepared) - 22
    people = len({i.participant for i in items})
    what = "1 opportunity" if len(items) == 1 else f"{len(items)} opportunities"
    who = f"one of {company}'s executives" if people == 1 else f"{people} of {company}'s executives"
    intro = (
        f"{what} from {who}, placed by the value they expect and how ready the organization is today "
        "(data, workflow, owner and controls). Here is where to start."
    )
    y = _text(c, MARGIN, y, _lines(intro, "Helvetica", 9.5, CONTENT_W, 2), "Helvetica", 9.5, MUTED, 13) - 6
    y = _stats(c, y, items) - 14

    # Size the two action panels to their content first; the map takes the rest of the page.
    gap = 12
    w = (CONTENT_W - gap) / 2
    act = _ranked([i for i in items if i.quadrant == "act_now"])[:3]
    fix = _ranked([i for i in items if i.quadrant == "strategic"])[:3]
    start = _Panel(
        "Start in the next 90 days",
        QUADRANTS["act_now"][1],
        [
            [
                (i.title, "Helvetica-Bold", 9, INK, 2),
                (
                    f"Owner: {i.owner or 'to be named'}  |  Proposed by {i.participant}",
                    "Helvetica",
                    8,
                    MUTED,
                    1,
                ),
                (i.next_step or "First step to be agreed.", "Helvetica", 8.5, INK, 2),
            ]
            for i in act
        ],
        "Nothing is ready on both value and readiness yet. Start with the foundations on the right.",
        w,
    )
    first = _Panel(
        "Fix first",
        QUADRANTS["strategic"][1],
        [
            [
                (i.title, "Helvetica-Bold", 9, INK, 2),
                (f"Held back by: {_blockers(i)}", "Helvetica", 8, MUTED, 1),
                (
                    f"Depends on: {i.dependencies}" if i.dependencies else i.next_step or "",
                    "Helvetica",
                    8.5,
                    INK,
                    2,
                ),
            ]
            for i in fix
        ],
        "No high-value initiative is waiting on foundations.",
        w,
    )
    footer_top = 76
    panel_h = max(start.height, first.height, 110)
    grid_h = max(y - footer_top - panel_h - 14, 200)
    y = _grid(c, y, items, grid_h) - 14
    panel_h = min(panel_h, y - footer_top)
    start.draw(c, MARGIN, y, panel_h)
    first.draw(c, MARGIN + w + gap, y, panel_h)

    c.setStrokeColor(RULE)
    c.line(MARGIN, 62, PAGE_W - MARGIN, 62)
    c.setFillColor(INK)
    c.setFont("Helvetica-Bold", 8.5)
    c.drawString(
        MARGIN, 48, "Follow-on support (assessment, roadmap, pilot) is optional and comes with no commitment."
    )
    note = (
        f"Captured in the Medicare Advantage AI Executive Simulation. Scores are the executives' own estimates. "
        f"This map belongs to {company} and shows only opportunities its executives chose to share."
    )
    _text(c, MARGIN, 36, _lines(note, "Helvetica", 7.5, CONTENT_W, 2), "Helvetica", 7.5, MUTED, 10)
    c.showPage()
    c.save()
    return buffer.getvalue()


def team_onepager(
    game: GameService, session_id: str, team_id: str, item_ids: Sequence[str] | None = None
) -> tuple[str, bytes]:
    """(company name, PDF) for one team. `item_ids` limits the page to the facilitator's selection."""
    if not game.options.opportunity_onepager:
        raise OnePagerDisabled("The one-page export is switched off in Settings")
    team = next((t for t in game.session_view(session_id).teams if t.team_id == team_id), None)
    if team is None:
        raise NotFound("Team not found in this session")
    items = [i for i in game.opportunity_map(session_id).items if i.team == team.team_name]
    if item_ids is not None:
        wanted = set(item_ids)
        unknown = wanted - {i.id for i in items}
        if unknown:
            raise NotFound("Some selected opportunities are not on this company's map")
        items = [i for i in items if i.id in wanted]
    if not items:
        raise NotFound("This company has no shared opportunities to export")
    return team.team_name, render_onepager(team.team_name, items)
